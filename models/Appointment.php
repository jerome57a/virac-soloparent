<?php
require_once __DIR__ . '/Model.php';
require_once __DIR__ . '/../services/InterviewDateFeature.php';

/**
 * The appointments (interviews) staff schedule. Status: BOOKED -> COMPLETED |
 * MISSED | CANCELLED. Older rows may still carry a slot_id; new schedules are
 * saved without one (slot_id NULL).
 */
class Appointment extends Model
{
    public const STATUSES = ['BOOKED', 'COMPLETED', 'CANCELLED', 'MISSED'];

    /** New results start with an explicit outcome; earlier free-text results remain readable. */
    public static function interviewOutcome(?array $appointment): ?string
    {
        $result = trim((string) ($appointment['result'] ?? ''));
        foreach (['Successful', 'Unsuccessful'] as $outcome) {
            if ($result === $outcome || str_starts_with($result, $outcome . ': ')) {
                return $outcome;
            }
        }
        return null;
    }

    public static function interviewSuccessful(?array $appointment): bool
    {
        return $appointment && $appointment['status'] === 'COMPLETED'
            && trim((string) ($appointment['result'] ?? '')) !== '' && !empty($appointment['result_recorded_at'])
            && self::interviewOutcome($appointment) !== 'Unsuccessful';
    }

    /** Staff (re)schedule an interview directly (no slot); clears any old result/reminder/cancellation. */
    public function upsertStaffScheduled(int $applicationId, string $scheduledAt, string $location, ?string $notes, int $staffId): void
    {
        // An existing date-only row (date_only = 1) is converted to a timed appointment. Whether the row is date-only,
        // and which of the date-booking columns exist, is read from the row itself (SELECT *), so this needs no schema
        // probe, ignores the rollout flag, and never names a column the table does not have: an unmigrated table
        // returns no date_only key and takes the legacy statement below, byte for byte as before.
        $existing = $this->pdo->prepare('SELECT * FROM appointments WHERE application_id = ? FOR UPDATE');
        $existing->execute([$applicationId]);
        $row = $existing->fetch();
        if (is_array($row) && interview_is_date_only($row)) {
            $convert = 'date_only = 0'
                . (array_key_exists('booking_source', $row) ? ", booking_source = 'STAFF'" : '')
                . (array_key_exists('confirmation_sms_log_id', $row) ? ', confirmation_sms_log_id = NULL' : '');
            $this->pdo->prepare(
                'UPDATE appointments SET slot_id = NULL, scheduled_at = ?, location = ?, status = \'BOOKED\', notes = ?, scheduled_by = ?,
                     result = NULL, result_recorded_at = NULL, reminder_sent_at = NULL, interview_sms_log_id = NULL,
                     cancelled_at = NULL, cancelled_by = NULL, cancel_reason = NULL, ' . $convert . '
                 WHERE application_id = ?'
            )->execute([$scheduledAt, $location, $notes, $staffId, $applicationId]);
            return;
        }
        $this->pdo->prepare(
            'INSERT INTO appointments (application_id, slot_id, scheduled_at, location, notes, scheduled_by, reminder_sent_at)
             VALUES (?, NULL, ?, ?, ?, ?, NULL)
             ON DUPLICATE KEY UPDATE slot_id = NULL, scheduled_at = VALUES(scheduled_at), location = VALUES(location), status = \'BOOKED\',
                 notes = VALUES(notes), scheduled_by = VALUES(scheduled_by), result = NULL, result_recorded_at = NULL,
                 reminder_sent_at = NULL, interview_sms_log_id = NULL, cancelled_at = NULL, cancelled_by = NULL, cancel_reason = NULL'
        )->execute([$applicationId, $scheduledAt, $location, $notes, $staffId]);
    }

    /**
     * The applicant books an interview DATE (no time): the application's single appointment row becomes a BOOKED date-only
     * row at 00:00:00 (source $source), clearing any earlier result, reminder, SMS link and cancellation. interview_date
     * is generated by the database and never written. Only called when the date-booking schema is ready (the booking
     * service checks InterviewDateFeature::enabled() first), so it may name the date-booking columns.
     */
    public function bookDateOnly(int $applicationId, string $date, string $location, string $source = 'APPLICANT', ?int $scheduledBy = null): void
    {
        $this->pdo->prepare(
            'INSERT INTO appointments (application_id, slot_id, scheduled_at, date_only, booking_source, location, status, scheduled_by, reminder_sent_at)
             VALUES (?, NULL, ?, 1, ?, ?, \'BOOKED\', ?, NULL)
             ON DUPLICATE KEY UPDATE slot_id = NULL, scheduled_at = VALUES(scheduled_at), date_only = 1, booking_source = VALUES(booking_source),
                 location = VALUES(location), status = \'BOOKED\', notes = NULL, scheduled_by = VALUES(scheduled_by), result = NULL, result_recorded_at = NULL,
                 reminder_sent_at = NULL, interview_sms_log_id = NULL, confirmation_sms_log_id = NULL,
                 cancelled_at = NULL, cancelled_by = NULL, cancel_reason = NULL'
        )->execute([$applicationId, $date . ' 00:00:00', $source, $location, $scheduledBy]);
    }

    public function recordResult(int $applicationId, string $result): void
    {
        $this->pdo->prepare("UPDATE appointments SET result = ?, result_recorded_at = NOW(), status = 'COMPLETED' WHERE application_id = ?")
            ->execute([$result, $applicationId]);
    }

    /** Marks a BOOKED appointment CANCELLED (frees its seat). $cancelledBy is the user who cancelled. */
    public function cancel(int $appointmentId, int $cancelledBy, string $reason): void
    {
        $this->pdo->prepare("UPDATE appointments SET status = 'CANCELLED', cancelled_at = NOW(), cancelled_by = ?, cancel_reason = ? WHERE id = ? AND status = 'BOOKED'")
            ->execute([$cancelledBy, $reason, $appointmentId]);
    }

    public function markMissed(int $appointmentId): void
    {
        $this->pdo->prepare("UPDATE appointments SET status = 'MISSED' WHERE id = ? AND status = 'BOOKED'")->execute([$appointmentId]);
    }

    public function interviewFor(int $applicationId): ?array
    {
        $stmt = $this->pdo->prepare('SELECT * FROM appointments WHERE application_id = ?');
        $stmt->execute([$applicationId]);
        return $stmt->fetch() ?: null;
    }

    /**
     * Records the date-booking confirmation SMS (sms_logs id) on the application's BOOKED date-only appointment. Only
     * called when the date-booking schema is ready (after an applicant booking); a row that changed since (rescheduled by
     * staff, cancelled) is left alone.
     */
    public function linkConfirmationSms(int $applicationId, ?int $smsLogId): void
    {
        $this->pdo->prepare("UPDATE appointments SET confirmation_sms_log_id = ? WHERE application_id = ? AND status = 'BOOKED' AND date_only = 1")
            ->execute([$smsLogId, $applicationId]);
    }

    public function linkSmsLog(int $applicationId, ?int $smsLogId): void
    {
        $this->pdo->prepare('UPDATE appointments SET interview_sms_log_id = ? WHERE application_id = ?')
            ->execute([$smsLogId, $applicationId]);
    }

    public function interviewSms(int $applicationId): ?array
    {
        $stmt = $this->pdo->prepare('SELECT s.* FROM appointments i JOIN sms_logs s ON s.id = i.interview_sms_log_id WHERE i.application_id = ?');
        $stmt->execute([$applicationId]);
        return $stmt->fetch() ?: null;
    }

    /** One appointment with its application's reference, applicant and contact details. */
    public function findWithApplication(int $appointmentId): ?array
    {
        $stmt = $this->pdo->prepare(
            'SELECT i.*, a.reference_no, a.full_name, a.user_id, a.mobile, a.status AS application_status
             FROM appointments i JOIN applications a ON a.id = i.application_id WHERE i.id = ?'
        );
        $stmt->execute([$appointmentId]);
        return $stmt->fetch() ?: null;
    }

    /** Next $limit booked interviews after today; today's day sheet is listed separately. */
    public function upcomingInterviews(int $limit): array
    {
        return $this->pdo->query(
            "SELECT i.*, a.reference_no, a.full_name FROM appointments i
             JOIN applications a ON a.id = i.application_id
             WHERE i.scheduled_at >= DATE_ADD(CURDATE(), INTERVAL 1 DAY) AND i.status = 'BOOKED' ORDER BY i.scheduled_at ASC LIMIT " . (int) $limit
        )->fetchAll();
    }

    // ---- Date-only lifecycle rules (Manila calendar days) ----
    // A date-only appointment (date_only = 1) is stored at 00:00:00 and is "today's" all day. Timed rows keep
    // the exact comparisons the screens used before. These read the row's own date_only value, so they need no
    // schema check (a row without the key is timed).

    /** Today's date (Y-m-d) in Manila, or the date of $now (a Unix timestamp, for tests). */
    public static function manilaDate(?int $now = null): string
    {
        return (new DateTimeImmutable('@' . ($now ?? time())))->setTimezone(new DateTimeZone('Asia/Manila'))->format('Y-m-d');
    }

    /** Result can be recorded: timed => its time has arrived (as before); date-only => its date is today or earlier. */
    public static function canRecordResult(array $appointment, ?int $now = null): bool
    {
        if (interview_is_date_only($appointment)) {
            return substr((string) $appointment['scheduled_at'], 0, 10) <= self::manilaDate($now);
        }
        return strtotime((string) $appointment['scheduled_at']) <= ($now ?? time());
    }

    /** May be marked MISSED: timed => its time has arrived (as before); date-only => its date has passed (before today). */
    public static function canMarkMissed(array $appointment, ?int $now = null): bool
    {
        if (interview_is_date_only($appointment)) {
            return substr((string) $appointment['scheduled_at'], 0, 10) < self::manilaDate($now);
        }
        return strtotime((string) $appointment['scheduled_at']) <= ($now ?? time());
    }

    /**
     * Display only (applicant "next appointment"): timed => its time has not passed (as before); date-only => its
     * date is today or later. Does not affect any cancellation or booking rule.
     */
    public static function isStillAhead(?string $scheduledAt, bool $dateOnly, ?int $now = null): bool
    {
        if ($dateOnly) {
            return substr((string) $scheduledAt, 0, 10) >= self::manilaDate($now);
        }
        return strtotime((string) $scheduledAt) >= ($now ?? time());
    }

    /** Staff "today" list: a BOOKED timed appointment whose time has passed moves to Needs Outcome; a date-only one stays all day. */
    public static function staysOnTodayList(array $appointment, ?int $now = null): bool
    {
        return !($appointment['status'] === 'BOOKED' && !interview_is_date_only($appointment)
            && strtotime((string) $appointment['scheduled_at']) < ($now ?? time()));
    }

    /**
     * Today's appointments in any status except CANCELLED (the staff day sheet). "Today" is the Manila date,
     * passed from PHP. If the date_only column's existence cannot be established the list is empty (fail closed).
     */
    public function todaysInterviews(): array
    {
        if (InterviewDateFeature::dateOnlyColumnPresence($this->pdo) === 'unknown') {
            return [];
        }
        $stmt = $this->pdo->prepare(
            "SELECT i.*, a.reference_no, a.full_name, a.id AS application_id
             FROM appointments i JOIN applications a ON a.id = i.application_id
             WHERE DATE(i.scheduled_at) = ? AND i.status <> 'CANCELLED' ORDER BY i.scheduled_at"
        );
        $stmt->execute([self::manilaDate()]);
        return $stmt->fetchAll();
    }

    /** Booked appointments after today (up to 100), grouped by Y-m-d date. */
    public function laterInterviewsByDate(): array
    {
        $rows = $this->pdo->query(
            "SELECT i.*, a.reference_no, a.full_name, a.id AS application_id
             FROM appointments i JOIN applications a ON a.id = i.application_id
             WHERE DATE(i.scheduled_at) > CURDATE() AND i.status = 'BOOKED'
             ORDER BY i.scheduled_at LIMIT 100"
        )->fetchAll();
        $byDate = [];
        foreach ($rows as $iv) {
            $byDate[date('Y-m-d', strtotime($iv['scheduled_at']))][] = $iv;
        }
        return $byDate;
    }

    /**
     * Appointments whose time has passed but are still BOOKED: staff must record the result or mark them missed. Oldest first.
     * A date-only appointment counts only once its Manila date has passed. Column present => date-only-aware SQL;
     * absent (unmigrated) => the legacy query; unknown => empty (fail closed).
     */
    public function awaitingOutcome(): array
    {
        $presence = InterviewDateFeature::dateOnlyColumnPresence($this->pdo);
        if ($presence === 'unknown') {
            return [];
        }
        if ($presence === 'present') {
            $stmt = $this->pdo->prepare(
                "SELECT i.*, a.reference_no, a.full_name, a.id AS application_id
                 FROM appointments i JOIN applications a ON a.id = i.application_id
                 WHERE i.status = 'BOOKED'
                   AND ((i.date_only = 0 AND i.scheduled_at < NOW()) OR (i.date_only = 1 AND i.scheduled_at < ?))
                 ORDER BY i.scheduled_at LIMIT 100"
            );
            $stmt->execute([self::manilaDate() . ' 00:00:00']);
            return $stmt->fetchAll();
        }
        return $this->pdo->query(
            "SELECT i.*, a.reference_no, a.full_name, a.id AS application_id
             FROM appointments i JOIN applications a ON a.id = i.application_id
             WHERE i.status = 'BOOKED' AND i.scheduled_at < NOW() ORDER BY i.scheduled_at LIMIT 100"
        )->fetchAll();
    }

    /** Includes cancelled/no-show applicants so replacement scheduling has a visible next step. */
    public function awaitingStaffSchedule(): array
    {
        return $this->pdo->query("SELECT a.id, a.reference_no, a.full_name, i.status AS appointment_status
            FROM applications a LEFT JOIN appointments i ON i.application_id = a.id
            WHERE a.status IN ('Pending Review','Under Verification','For Revision','Interview Scheduled')
              AND a.renewal_simplified = 0 AND (i.id IS NULL OR i.status IN ('MISSED','CANCELLED'))
            ORDER BY a.submitted_at,a.id LIMIT 100")->fetchAll();
    }

    /**
     * BOOKED appointments within the next $hours that haven't been reminded yet. These are the timed reminders:
     * a date-only appointment (date_only = 1) has no time of day, so it never enters this workflow. The exclusion
     * depends only on the appointments.date_only column existing (never on the rollout flag): present => the
     * date_only = 0 condition is added; proven absent (unmigrated database) => the exact legacy query; unknown
     * (existence could not be established) => nothing is returned or marked, so a later run retries, because a
     * wrongly sent reminder cannot be undone.
     */
    public function dueForReminder(int $hours): array
    {
        $presence = InterviewDateFeature::dateOnlyColumnPresence($this->pdo);
        if ($presence === 'unknown') {
            return [];
        }
        $timedOnly = $presence === 'present' ? "\n               AND i.date_only = 0" : '';
        $stmt = $this->pdo->prepare(
            "SELECT i.id AS interview_id, i.scheduled_at, i.location, a.id AS application_id, a.user_id, a.reference_no, a.mobile
             FROM appointments i JOIN applications a ON a.id = i.application_id
             WHERE i.status = 'BOOKED'
               AND i.scheduled_at > NOW()
               AND i.scheduled_at <= DATE_ADD(NOW(), INTERVAL ? HOUR)
               AND i.reminder_sent_at IS NULL" . $timedOnly
        );
        $stmt->execute([$hours]);
        return $stmt->fetchAll();
    }

    /**
     * BOOKED date-only appointments (date_only = 1) not yet reminded whose date is today (Manila) or later. They are not
     * filtered by time: AppointmentService decides when each is due (its previous-office-day reminder instant). Like
     * dueForReminder() it depends only on the date_only column existing, never on the rollout flag: present => queried;
     * absent (unmigrated) or unknown => nothing is returned or marked, so a later run retries.
     */
    public function dueDateOnlyForReminder(): array
    {
        if (InterviewDateFeature::dateOnlyColumnPresence($this->pdo) !== 'present') {
            return [];
        }
        $stmt = $this->pdo->prepare(
            "SELECT i.id AS interview_id, i.scheduled_at, i.location, a.id AS application_id, a.user_id, a.reference_no, a.mobile
             FROM appointments i JOIN applications a ON a.id = i.application_id
             WHERE i.status = 'BOOKED' AND i.date_only = 1 AND i.reminder_sent_at IS NULL AND i.scheduled_at >= ?"
        );
        $stmt->execute([self::manilaDate() . ' 00:00:00']);
        return $stmt->fetchAll();
    }

    public function markReminded(int $interviewId): void
    {
        $this->pdo->prepare('UPDATE appointments SET reminder_sent_at = NOW() WHERE id = ?')->execute([$interviewId]);
    }
}
